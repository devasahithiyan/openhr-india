import { URL } from "node:url";
// Vercel builds prototype/ independently. Vendor the pure model and presentation,
// leaving session, persistence and permissions to each app's adapter.
import { readFile, writeFile } from "node:fs/promises";
const files = [
  ["packages/shared/src/onboarding-model.ts", "model.ts"],
  ["packages/shared/src/workforce.ts", "../workforce/model.ts"],
  ["apps/web/components/workforce-board.tsx", "../workforce/board.tsx"],
  ["apps/web/components/onboarding-board.tsx", "board.tsx"],
];
for (const [source, name] of files) {
  const root = new URL("../", import.meta.url);
  const body =
    "// Generated by scripts/sync-onboarding.mjs\n" +
    (await readFile(new URL(source, root), "utf8")).replaceAll(
      '"@openhr/shared"',
      '"./model"',
    );
  const target = new URL("prototype/src/onboarding/" + name, root);
  if (process.argv.includes("--check")) {
    if ((await readFile(target, "utf8")) !== body)
      throw new Error("Run node scripts/sync-onboarding.mjs");
  } else await writeFile(target, body);
}
